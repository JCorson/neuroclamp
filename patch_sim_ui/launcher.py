"""Prepare a working directory and start the web UI from an installed package.

Reflex resolves its configuration, static assets and frontend build directory
relative to the current working directory, so ``reflex run`` only works from a
source checkout. The ``patch-sim ui`` command instead runs Reflex in a writable
per-user directory that holds:

- ``rxconfig.py``: a stub that re-exports ``patch_sim_ui._rxconfig.config``.
  No top-level ``rxconfig`` module is installed, so the app does not collide
  with other Reflex apps in the same environment.
- ``assets/screenshots/``: the help-page screenshots, copied from the package.
- ``.web/``: the frontend build, created by Reflex on first run.
- ``.patch-sim-workdir``: a marker identifying the directory as the
  launcher's. The launcher refuses to write into, or delete, a non-empty
  directory without it, so a mistyped ``--workdir`` cannot clobber user files.

The directory is keyed by package version, so an upgrade starts from a clean
frontend build. Reflex itself is not imported here; it runs in a child
process, and the helpers that need ``platformdirs`` import it lazily so that
this module loads without the ``ui`` extra.
"""

import http.client
import logging
import os
import shlex
import shutil
import signal
import socket
import subprocess
import sys
import threading
import time
import urllib.error
import urllib.request
import webbrowser
from collections.abc import Callable, Mapping
from pathlib import Path

#: Contents of the ``rxconfig.py`` written into the working directory.
RXCONFIG_STUB = '''"""Reflex configuration generated by patch-sim; do not edit."""

from patch_sim_ui._rxconfig import config

__all__ = ["config"]
'''

#: Environment defaults for the Reflex child process. Users can override
#: either by setting the variable before running ``patch-sim ui``.
CHILD_ENV_DEFAULTS: dict[str, str] = {
    "REFLEX_TELEMETRY_ENABLED": "false",
    "REFLEX_CHECK_LATEST_VERSION": "false",
}

#: File that marks a directory as a launcher working directory.
WORKDIR_MARKER = ".patch-sim-workdir"

#: Seconds to wait for the server to shut down before killing it.
SHUTDOWN_GRACE_SECONDS = 30.0

_PACKAGE_DIR = Path(__file__).resolve().parent

logger = logging.getLogger(__name__)


class LauncherError(Exception):
    """A problem that stops the launcher, reported to the user without a traceback."""


class _Terminated(Exception):
    """Raised in the main thread when the launcher receives SIGTERM."""


def default_workdir(version: str) -> Path:
    """Return the per-user working directory for a package version.

    Args:
        version: The installed ``patch-sim`` version.

    Returns:
        ``<user cache dir>/patch-sim/<version>``, for example
        ``~/.cache/patch-sim/0.1.0`` on Linux.
    """
    import platformdirs

    return Path(platformdirs.user_cache_dir("patch-sim", appauthor=False)) / version


def find_screenshots_dir() -> Path | None:
    """Locate the help-page screenshots that ship with the UI.

    A built wheel carries them at ``patch_sim_ui/_web_assets/screenshots``. An
    editable install or a source checkout reads them from the repository-root
    ``assets/screenshots``.

    Returns:
        The screenshots directory, or ``None`` if neither location exists.
    """
    for candidate in (
        _PACKAGE_DIR / "_web_assets" / "screenshots",
        _PACKAGE_DIR.parent / "assets" / "screenshots",
    ):
        if candidate.is_dir():
            return candidate
    return None


def prepare_workdir(
    workdir: Path, screenshots: Path | None, reset: bool = False
) -> Path:
    """Create or refresh the directory Reflex runs in.

    ``rxconfig.py`` is rewritten only when its content differs, and
    ``assets/`` is replaced on every call so files removed from the package do
    not linger. The ``.web/`` frontend build is kept between runs unless
    ``reset`` is set.

    Args:
        workdir: Directory to prepare; created if missing.
        screenshots: Directory of help-page screenshots to copy into
            ``assets/screenshots``, or ``None`` to skip them.
        reset: Delete the whole directory first, forcing a fresh frontend
            build.

    Returns:
        The prepared working directory.

    Raises:
        LauncherError: If the directory cannot be created or written, or if it
            is a non-empty directory the launcher did not create.
    """
    try:
        if (
            workdir.is_dir()
            and any(workdir.iterdir())
            and not (workdir / WORKDIR_MARKER).is_file()
        ):
            raise LauncherError(
                f"{workdir} is not empty and is not a patch-sim working "
                "directory. Choose a new or empty directory with --workdir."
            )
        if reset and workdir.exists():
            logger.debug("Deleting %s for a fresh build", workdir)
            shutil.rmtree(workdir)
        workdir.mkdir(parents=True, exist_ok=True)
        (workdir / WORKDIR_MARKER).touch()

        rxconfig = workdir / "rxconfig.py"
        if not rxconfig.is_file() or rxconfig.read_text() != RXCONFIG_STUB:
            logger.debug("Writing %s", rxconfig)
            rxconfig.write_text(RXCONFIG_STUB)
        else:
            logger.debug("%s is up to date", rxconfig)

        assets = workdir / "assets"
        if assets.exists():
            shutil.rmtree(assets)
        assets.mkdir()
        if screenshots is not None:
            logger.debug("Copying screenshots from %s", screenshots)
            shutil.copytree(screenshots, assets / "screenshots")
    except OSError as exc:
        raise LauncherError(
            f"Cannot prepare the working directory {workdir}: {exc}. "
            "Choose a writable location with --workdir."
        ) from exc
    return workdir


def _can_bind(family: socket.AddressFamily, port: int) -> bool:
    """Report whether a TCP socket can bind the wildcard address on a port.

    Args:
        family: Address family to test.
        port: TCP port to bind; 0 picks any free port.

    Returns:
        ``True`` if the bind succeeds.
    """
    try:
        with socket.socket(family, socket.SOCK_STREAM) as sock:
            if sys.platform != "win32":
                # Ignore sockets left in TIME_WAIT by a server that just
                # stopped. On Windows this option would allow binding a port
                # in active use.
                sock.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
            sock.bind(("", port))
    except OSError:
        return False
    return True


def port_in_use(port: int) -> bool:
    """Report whether a TCP port is taken, using the same test as Reflex.

    Reflex refuses to start if it cannot bind the port on the wildcard address
    of every usable address family (IPv4 and, where available, IPv6),
    whichever host it will serve on. Mirroring that test here reports a
    conflict before the first-run frontend build rather than minutes after.

    Args:
        port: TCP port the server will listen on.

    Returns:
        ``True`` if any usable address family cannot bind the port.
    """
    families = [
        family for family in (socket.AF_INET, socket.AF_INET6) if _can_bind(family, 0)
    ]
    busy = [family.name for family in families if not _can_bind(family, port)]
    logger.debug(
        "Port %d checked on %s; busy on %s",
        port,
        ", ".join(family.name for family in families),
        ", ".join(busy) or "none",
    )
    return bool(busy)


def check_host(host: str) -> None:
    """Check that a bind host is a resolvable address.

    Args:
        host: Interface address the server will bind to.

    Raises:
        LauncherError: If the address cannot be resolved.
    """
    try:
        socket.getaddrinfo(host, None)
    except (socket.gaierror, UnicodeError) as exc:
        raise LauncherError(f"Cannot use --host {host!r}: {exc}.") from exc


def browser_url(host: str, port: int) -> str:
    """Return the URL a local browser should open for the server.

    Reflex's API URL defaults to ``http://localhost:<port>``, and the figure
    and CSV-export requests go to that absolute URL. A page opened at
    ``127.0.0.1`` would make those requests cross-origin, which the production
    server does not allow, so loopback and wildcard hosts open as
    ``localhost``.

    Args:
        host: Interface address the server binds to.
        port: TCP port the server listens on.

    Returns:
        The app URL. Loopback and wildcard hosts (``127.0.0.1``, ``::1``,
        ``0.0.0.0``, ``::`` or empty) map to ``localhost``.
    """
    if host in ("", "0.0.0.0", "::", "127.0.0.1", "::1"):
        host = "localhost"
    elif ":" in host:
        host = f"[{host}]"
    return f"http://{host}:{port}"


def build_reflex_command(host: str, port: int) -> list[str]:
    """Return the command that runs the app in production, single-port mode.

    Args:
        host: Interface address for the server to bind to.
        port: TCP port that serves both the frontend and the backend.

    Returns:
        The argument list for ``subprocess``.
    """
    return [
        sys.executable,
        "-m",
        "reflex",
        "run",
        "--env",
        "prod",
        "--single-port",
        "--frontend-port",
        str(port),
        "--backend-host",
        host,
    ]


def build_child_env(base: Mapping[str, str]) -> dict[str, str]:
    """Return the environment for the Reflex child process.

    Args:
        base: The launcher's environment, usually ``os.environ``.

    Returns:
        A copy of ``base`` with :data:`CHILD_ENV_DEFAULTS` filled in where the
        variables are not already set.
    """
    env = dict(base)
    for key, value in CHILD_ENV_DEFAULTS.items():
        env.setdefault(key, value)
    return env


def _server_ready(url: str) -> bool:
    """Report whether the backend answers its health-check endpoint.

    Args:
        url: Base URL of the app.

    Returns:
        ``True`` if ``<url>/ping`` responds with HTTP 200.
    """
    try:
        with urllib.request.urlopen(f"{url}/ping", timeout=2) as response:
            return response.status == 200
    except (urllib.error.URLError, http.client.HTTPException, OSError):
        return False


def _has_graphical_browser() -> bool:
    """Report whether opening a browser would show a graphical window.

    On Linux without a display (an SSH session or a container), ``webbrowser``
    falls back to a console browser that would take over the terminal running
    the server.

    Returns:
        ``False`` on Linux when neither ``DISPLAY`` nor ``WAYLAND_DISPLAY`` is
        set; ``True`` otherwise.
    """
    if sys.platform.startswith("linux"):
        return bool(os.environ.get("DISPLAY") or os.environ.get("WAYLAND_DISPLAY"))
    return True


def _on_sigterm(signum: int, frame: object) -> None:
    """Turn SIGTERM into an exception so the server is shut down first.

    Args:
        signum: The received signal number.
        frame: The interrupted stack frame.

    Raises:
        _Terminated: Always.
    """
    raise _Terminated


def _stop_server(proc: subprocess.Popen, already_signaled: bool) -> None:
    """Stop the server process, escalating to a kill if it does not exit.

    Args:
        proc: The Reflex server process.
        already_signaled: ``True`` when the server already received the
            interrupt (Ctrl+C reaches the whole process group), so it only
            needs time to shut down; otherwise it is sent SIGTERM first.
    """
    if proc.poll() is not None:
        return
    logger.info("Stopping the server...")
    try:
        if not already_signaled:
            logger.debug("Sending SIGTERM to the server (pid %d)", proc.pid)
            proc.terminate()
        proc.wait(timeout=SHUTDOWN_GRACE_SECONDS)
    except (KeyboardInterrupt, subprocess.TimeoutExpired):
        logger.warning("The server did not stop; killing it.")
        proc.kill()
        proc.wait()


def open_browser_when_ready(
    url: str,
    proc_alive: Callable[[], bool],
    timeout: float = 900.0,
    poll_interval: float = 1.0,
) -> threading.Thread:
    """Open the app in a browser once the server responds.

    The first run builds the frontend, which can take minutes, so the browser
    opens only after the server answers rather than after a fixed delay.

    Args:
        url: Base URL of the app.
        proc_alive: Returns ``False`` once the server process has exited, which
            stops the wait.
        timeout: Seconds to wait before giving up.
        poll_interval: Seconds between readiness checks.

    Returns:
        The started daemon thread.
    """

    def _wait_and_open() -> None:
        """Poll the server and open the browser when it is ready."""
        logger.debug("Waiting for %s/ping before opening the browser", url)
        deadline = time.monotonic() + timeout
        while proc_alive() and time.monotonic() < deadline:
            if _server_ready(url):
                logger.debug("Server is ready; opening %s", url)
                webbrowser.open(url)
                return
            time.sleep(poll_interval)
        if proc_alive():
            logger.warning(
                "The server did not respond within %.0f seconds; open %s "
                "yourself once it is ready.",
                timeout,
                url,
            )
        else:
            logger.debug("Server exited before it was ready; no browser opened")

    thread = threading.Thread(target=_wait_and_open, daemon=True)
    thread.start()
    return thread


def run_ui(
    workdir: Path,
    host: str,
    port: int,
    open_browser: bool = True,
    reset: bool = False,
) -> int:
    """Prepare the working directory and run the web UI until it exits.

    Args:
        workdir: Directory Reflex runs in.
        host: Interface address for the server to bind to.
        port: TCP port for the server.
        open_browser: Open the app in the default browser once it is ready.
        reset: Delete ``workdir`` first, forcing a fresh frontend build.

    Returns:
        The server's exit code, 130 if interrupted with Ctrl+C, or 143 if
        stopped with SIGTERM. Either signal shuts the server down before the
        launcher exits.

    Raises:
        LauncherError: If the host is invalid, the port is taken, or
            ``workdir`` cannot be used.
    """
    check_host(host)
    if port_in_use(port):
        raise LauncherError(
            f"Port {port} is already in use. Choose another with --port."
        )

    screenshots = find_screenshots_dir()
    if screenshots is None:
        logger.warning(
            "Help-page screenshots not found; /help will show broken images."
        )
    first_run = reset or not (workdir / ".web").is_dir()
    prepare_workdir(workdir, screenshots, reset=reset)

    url = browser_url(host, port)
    if first_run:
        logger.info(
            "First launch builds the web frontend. This can take a few minutes "
            "and needs internet access."
        )
    logger.info("Starting patch-sim at %s (working directory: %s)", url, workdir)
    logger.info("Press Ctrl+C to stop.")

    command = build_reflex_command(host, port)
    logger.debug("Running %s", shlex.join(command))
    proc = subprocess.Popen(command, cwd=workdir, env=build_child_env(os.environ))
    if open_browser and _has_graphical_browser():
        open_browser_when_ready(url, lambda: proc.poll() is None)
    elif open_browser:
        logger.info("No display found; open %s in a browser.", url)

    # Signal handlers can only be installed from the main thread.
    in_main_thread = threading.current_thread() is threading.main_thread()
    previous_handler = (
        signal.signal(signal.SIGTERM, _on_sigterm) if in_main_thread else None
    )
    interrupted = False
    try:
        code = proc.wait()
        logger.debug("Server exited with code %d", code)
        return code
    except KeyboardInterrupt:
        interrupted = True
        return 130
    except _Terminated:
        logger.debug("Received SIGTERM")
        return 143
    finally:
        _stop_server(proc, already_signaled=interrupted)
        if previous_handler is not None:
            signal.signal(signal.SIGTERM, previous_handler)
